// Writes the Nginx site configuration for the production server (a Hostinger VPS) from
// deploy/headers.json, the one list of response headers. The browser tests serve the site
// with the same list, so what is tested locally is what Nginx sends.
//
//   npm run build:nginx          writes deploy/nginx/<domain>.conf
//   npm run build:nginx -- --check   fails if the committed file is out of date
//
// Nginx does not inherit add_header into a location that has its own, so every location
// below repeats the full set. That is why the file is generated and not written by hand.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const site = JSON.parse(readFileSync(resolve(ROOT, "content", "site.json"), "utf8"));
const { headers: RULES } = JSON.parse(readFileSync(resolve(ROOT, "deploy", "headers.json"), "utf8"));

export const DOMAIN = new URL(site.siteUrl).hostname;
// The deploy script (deploy/deploy.sh) keeps releases beside this link and repoints it.
export const APP_DIR = `/var/www/${DOMAIN}`;
export const CONFIG_PATH = resolve(ROOT, "deploy", "nginx", `${DOMAIN}.conf`);

const GLOBAL = "/(.*)";
const PREFIX = /^(\/[a-z0-9-]+\/)\(\.\*\)$/;

function quote(value) {
  if (/["$\\\n]/.test(value)) throw new Error(`Header value cannot be written safely for Nginx: ${value}`);
  return `"${value}"`;
}

// Headers for a path prefix: the global set, then that prefix's own, a later value for the
// same header replacing an earlier one. The same rule the test server applies.
function headersFor(source) {
  const merged = new Map();
  for (const rule of RULES) {
    if (rule.source !== GLOBAL && rule.source !== source) continue;
    for (const { key, value } of rule.headers) merged.set(key.toLowerCase(), { key, value });
  }
  return [...merged.values()];
}

// "always" sends the headers on error responses too, such as the 404 page.
const addHeaders = (source, indent) =>
  headersFor(source).map(({ key, value }) => `${indent}add_header ${key} ${quote(value)} always;`).join("\n");

export function nginxConfig() {
  const global = RULES.find((rule) => rule.source === GLOBAL);
  if (!global) throw new Error(`deploy/headers.json needs a rule for ${GLOBAL}`);
  const prefixes = RULES.filter((rule) => rule.source !== GLOBAL).map((rule) => {
    const match = rule.source.match(PREFIX);
    if (!match) throw new Error(`Unsupported source in deploy/headers.json: ${rule.source}. Use "/name/(.*)".`);
    return { source: rule.source, prefix: match[1] };
  });

  const locations = prefixes.map(({ source, prefix }) => `    location ${prefix} {
${addHeaders(source, "        ")}
        try_files $uri $uri/ =404;
    }`).join("\n\n");

  return `# GENERATED by scripts/build-nginx-config.mjs from deploy/headers.json. Do not edit:
# change deploy/headers.json and run \`npm run build:nginx\`.
#
# Install on the server as /etc/nginx/sites-available/${DOMAIN}.conf (DEPLOYMENT.md).
# It serves the built website only. The backend is Supabase; nothing is proxied.
# Needs the certificate from Let's Encrypt to exist first (certbot certonly).

# http:// goes to https:// on the bare domain.
server {
    listen 80;
    listen [::]:80;
    server_name ${DOMAIN} www.${DOMAIN};

    # Certificate renewal (certbot --webroot).
    location /.well-known/acme-challenge/ {
        root ${APP_DIR}/acme;
    }
    location / {
        return 301 https://${DOMAIN}$request_uri;
    }
}

# www goes to the bare domain, keeping the path.
server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name www.${DOMAIN};

    ssl_certificate /etc/letsencrypt/live/${DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${DOMAIN}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    server_tokens off;

    return 301 https://${DOMAIN}$request_uri;
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name ${DOMAIN};

    ssl_certificate /etc/letsencrypt/live/${DOMAIN}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${DOMAIN}/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    server_tokens off;

    # "current" is a link to the live release. Only built files are ever under it: never
    # point root at the repository, which holds development photos and the backend source.
    root ${APP_DIR}/current;
    index index.html;
    charset utf-8;
    # Redirects keep the host and scheme the visitor used (/menu -> /menu/).
    absolute_redirect off;
    error_page 404 /404.html;

    gzip on;
    gzip_comp_level 5;
    gzip_min_length 512;
    gzip_vary on;
    gzip_types text/css application/javascript text/javascript application/json image/svg+xml application/xml text/xml text/plain;

    # Nothing that starts with a dot is served.
    location ~ /\\. {
        return 404;
    }

${locations}

    # The not-found page is only ever shown for an address that does not exist.
    location = /404.html {
        internal;
${addHeaders(GLOBAL, "        ")}
    }

    location / {
${addHeaders(GLOBAL, "        ")}
        try_files $uri $uri/ =404;
    }
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const wanted = nginxConfig();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(CONFIG_PATH, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing */ }
    if (current !== wanted) {
      console.error(`${CONFIG_PATH} is out of date. Run \`npm run build:nginx\` and commit the result.`);
      process.exit(1);
    }
    console.log("The Nginx configuration matches deploy/headers.json.");
  } else {
    mkdirSync(dirname(CONFIG_PATH), { recursive: true });
    writeFileSync(CONFIG_PATH, wanted);
    console.log(`Wrote ${CONFIG_PATH}`);
  }
}
